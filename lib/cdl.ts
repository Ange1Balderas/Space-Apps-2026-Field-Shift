// Classes that say nothing about what grew: the raster's background and "Clouds/No Data".
// A year with one of these is treated as a year with no observation.
export const CDL_NO_OBSERVATION_CODES: ReadonlySet<number> = new Set([0, 81]);

/** The class name for a CDL code, or null when the code is not in USDA's table. */
export function cdlClassName(code: number): string | null {
	return CDL_CLASS_NAMES[code] ?? null;
}

/** True when the code names a real class: in the table, and not background or clouds. */
export function isObservedCdlClass(code: number): boolean {
	return cdlClassName(code) !== null && !CDL_NO_OBSERVATION_CODES.has(code);
}
